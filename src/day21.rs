use std::{collections::{HashMap, HashSet}, sync::Arc, time::SystemTime, usize};
use std::thread;

#[derive(Debug, PartialEq, Eq)]
enum Tile {
    Rock,
    Plot,
}
type Map = Vec<Vec<Tile>>;
type Pos = (i32, i32);
pub fn solve() {
    let (map, start) = parse();
    let map = Arc::new(map);
    //let mut pos_cache = HashMap::new();

    let t = SystemTime::now();
    println!("{TEST_INPUT}");
    //dbg!(map);
    let mut possible_states: HashSet<Pos> = vec![start].into_iter().collect();

    for i in 0..26501365 {
        let mut new_states = HashSet::new();
        let mut handles = Vec::new();
        for pos in possible_states.iter() {
            let pos = pos.clone();
            let map = map.clone();
            let handle = thread::spawn(move || {
                let mut c = HashMap::new();
                let r = travel(pos, &map, &mut c);
                return r;
            });
            handles.push(handle);
        }

        for h in handles {
            let r = h.join().unwrap();
            new_states.extend(r.iter());
        }

        possible_states = new_states;

        //println!("For iterm: {i}, states: {:?}", possible_states);
        println!("State: {}, size: {}", i+1, possible_states.len());
    }

    let tot = t.elapsed();
    println!("Total states: {}, Took time: {:?}", possible_states.len(), tot);
}


fn travel(pos: Pos, map: &Vec<Vec<Tile>>, pos_cache: &mut HashMap<Pos, Vec<Pos>>) -> Vec<Pos> {
    if let Some(list) = pos_cache.get(&pos) {
        return list.clone();
    }

    let i_len = map.len();
    let j_len = map.first().unwrap().len();
    let (i_abs, j_abs) = pos;

    //let i = if i_abs > 0 { i_abs as usize } else { i_len - (i_abs % j_len as i32).abs() as usize };
    let i = i_abs % i_len as i32;
    let i = (if i < 0 { i_len as i32 + i } else { i }) as usize;
    //let j = if j_abs > 0 { j_abs as usize } else { j_len - (j_abs % j_len as i32).abs() as usize };
    let j = j_abs % j_len as i32;
    let j = (if j < 0 { j_len as i32 + j } else { j }) as usize;
    let i_next = (i + 1) % i_len;
    let i_prev = if i == 0 { i_len -1 } else { (i - 1) % i_len };

    let j_next = (j + 1) % j_len;
    let j_prev = if j == 0 { j_len - 1 } else { (j - 1) % j_len };


    let mut valid_states = Vec::new();

    //println!("INPUT: i_len: {i_len}, j_len: {j_len}, i_abs: {i_abs}, j_abs: {j_abs}, i: {i}, j: {j}");
    //println!("Get ({}) -> {:?} , j {} -> {:?}", i_next, map.get(i_next), j, map.get(i_next).and_then(|r| r.get(j)));
    if map.get(i_next).and_then(|r| r.get(j)) == Some(&Tile::Plot) {
        valid_states.push((i_abs+1, j_abs));
    }

    if map.get(i_prev).and_then(|r| r.get(j)) == Some(&Tile::Plot) {
        valid_states.push((i_abs-1, j_abs));
    }

    if map.get(i).and_then(|r| r.get(j_next)) == Some(&Tile::Plot) {
        valid_states.push((i_abs, j_abs+1));
    }

    if map.get(i).and_then(|r| r.get(j_prev)) == Some(&Tile::Plot) {
        valid_states.push((i_abs, j_abs-1));
    }

    if i_abs < 0 || j_abs < 0 {
        //println!("FOr pos: ( {i_abs}, {j_abs} ) Got states {:?}", valid_states);
    }

    pos_cache.insert((i_abs,j_abs), valid_states.clone());
    return valid_states;
}

fn parse() -> (Vec<Vec<Tile>>, Pos) {
    let mut map = Vec::new();
    let lines = TEST_INPUT.lines();
    let _lines = INPUT.lines();

    let mut i = 0;
    let mut start = (0,0);
    for l in lines {

        let mut row = Vec::new();

        let mut j = 0;
        for c in l.chars() {
            if c == '.' {
                row.push(Tile::Plot);
            } else if c == '#' {
                row.push(Tile::Rock);
            } else if c == 'S' {
                row.push(Tile::Plot);
                println!("Start pos: {}-{}", i, j);
                start = (i,j)
            }

            j += 1;
        }

        map.push(row);
        i+=1;
    }

    return (map, start);
}

